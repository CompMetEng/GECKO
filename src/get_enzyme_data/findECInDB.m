function [EC,conflicts] = findECInDB(gene_set, DBecNum, DBMW, geneIndex, geneHashMap)
% findECInDB  Look up EC numbers for a reaction's gene set in a UniProt or KEGG index.
%
% For each gene, finds its matching database entries and takes the EC number
% of the lightest-weight matching protein when a single EC number applies to
% that gene; genes with several distinct EC numbers among their matches are
% also reported as conflicts (the first match is still used for EC). For a
% single gene, a wildcard code such as "1.1.1.-" is dropped when a more
% specific code of the same prefix ("1.1.1.4") is present; only codes with
% four levels take part, and empty codes are removed. When gene_set has more
% than one gene (an enzyme complex), the numbers found for each gene are
% combined by intersection where they share a match (wildcards such as "-"
% are accounted for), otherwise by union, and the combined set is not
% cleaned of a wildcard next to a specific code.
%
% Parameters
% ----------
% gene_set : cell
%     genes from a given metabolic reaction.
% DBecNum : cell
%     array of EC numbers.
% DBMW : double
%     array of molecular weights in Da.
% geneIndex : cell
%     as generated by getECfromDatabase.
% geneHashMap : containers.Map
%     as generated by getECfromDatabase.
%
% Returns
% -------
% EC : char
%     EC numbers that apply to gene_set, each prefixed with "EC" and
%     separated by ";" (e.g. "EC1.1.1.1;EC1.1.1.2").
% conflicts : cell
%     genes with multiple protein matches.
%
% Examples
% --------
%     [EC, conflicts] = findECInDB(gene_set, DBecNum, DBMW, geneIndex, geneHashMap);
%
% See also
% --------
% getECfromDatabase, getECstring

%Preallocate function variables
conflicts = cell(1,2);

%Split the gene set and match each gene:
%gene_set  = strsplit(grRule,' and '); %this string splitting together with getSimpleGeneSets takes 2.6 s, that is ok.
EC_set    = cell(size(gene_set));

%find index indices of all genes in one call

%this loop is slow
for j = 1:length(gene_set)
     gene = gene_set{j};
     matches = [];
     %Get the indexes for all of the proteins related to gene
     if isKey(geneHashMap,gene) %annoyingly, this seems to be needed
         matchInd = cell2mat(values(geneHashMap,gene_set(j)));
         matches = geneIndex{matchInd};
     end
     if ~isempty(matches)
        %Get the indexes of the matched protein(s) with non-empty EC#s
        nonEmpty = matches(~cellfun(@isempty,DBecNum(matches)));
        if ~isempty(nonEmpty)
            [geneECs,ia] = unique(DBecNum(nonEmpty),'stable');
            %For genes with multiple proteins associated to several
            %non-empty ecNumbers
            if length(geneECs)>1
                indexes = nonEmpty(ia);
                ecNum = DBecNum(indexes);
                %Save first match
                EC_set{j}  = getECstring(EC_set{j},ecNum{1});
                %Save additional matches as potential conflicts
                if ~ismember(gene,conflicts{1})
                    conflicts{1} = [conflicts{1}; {gene}];
                    conflicts{2} = [conflicts{2}; {indexes}]; 
                end
            else
                %If there is a single unique ec number for the matched
                %protein(s), then choose the lightest protein
                [~,minW]   = min(DBMW(nonEmpty));
                matches    = nonEmpty(minW);
                EC_set{j}  = getECstring(EC_set{j},DBecNum{matches});
            end
        end
    end

    if isempty(EC_set{j})
        EC_set{j} = '';
    end
end

%EC: Find union and intersection between all units (only applies for
%complexes, i.e. length(EC_set) > 1):
uni_EC = strsplit(EC_set{1},' ');
int_EC = uni_EC;
for j = 2:length(EC_set)
    other_EC = strsplit(EC_set{j},' ');
    if isempty(uni_EC)
        uni_EC = other_EC;
        int_EC = other_EC;
    elseif ~isempty(other_EC)
        uni_EC = compare_wild([uni_EC other_EC]);
        int_EC = intersection(int_EC,other_EC);
    end
end
%A single gene keeps no wildcard code next to a more specific code of the
%same prefix (e.g. 'EC1.1.1.-' next to 'EC1.1.1.4'):
if isscalar(EC_set)
    int_EC = dropWildcardParents(int_EC);
end
%Use the intersection found, if any. If not, use the union: 
if isempty(int_EC)
    EC_set = uni_EC;
else
    EC_set = int_EC;
end

%Add new codes as new possible isozymes and remove the initial "EC" text:

for i = 1:length(EC_set)
   if ~isempty(EC_set{i}) 
       EC_set{i} = extractAfter(EC_set{i},2);%remove 2 first chars
   end
end

%EC_set = cellfun(@(x) extractAfter(x,2),EC_set,'UniformOutput',false);%remove 2 first chars
EC    = strjoin(EC_set,';');


%Delete repeated Uniprots (and the corresponding ECs):
%EC(deleted)   = []; %Not sure if this needs to be done somehow, don't think so

end

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
function int_EC = intersection(prev_EC,new_EC)
%Finds the common elements between two cell arrays, if any. Also considers
%wildcards (e.g. if 'EC1.1.1.1' is in one array and 'EC1.1.1.-' is in the
%other one, then 'EC1.1.1.1' is added to the intersection).
int_EC = {};
for i = 1:length(prev_EC)
    for j = 1:length(new_EC)
        new_int = compare_wild({prev_EC{i} new_EC{j}});
        if length(new_int) == 1
            int_EC = [int_EC new_int];
        end
    end
end
%When prev_EC carries both a code and its own wildcard parent (e.g.
%'EC1.1.1.1' and 'EC1.1.1.-'), both independently pair-match the same
%new_EC entry above and the loop appends the resolved code twice; dedupe.
int_EC = unique(int_EC,'stable');
end
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
function int_EC = dropWildcardParents(EC)
%Removes empty codes and every code that is a wildcard parent of another
%code in the cell array (e.g. 'EC1.2.3.-' when 'EC1.2.3.4' is present). Only
%codes with four levels are compared, so 'EC1.1.1' is neither a parent nor a
%child of 'EC1.1.1.4'. Equal codes collapse to the first.
EC = EC(~cellfun(@isempty,EC) & ~strcmp(EC,'EC'));
keep = true(1,numel(EC));
for i = 1:numel(EC)
    if ~keep(i)
        continue;
    end
    for j = i+1:numel(EC)
        if ~keep(j)
            continue;
        end
        iInJ = subsumes(EC{i},EC{j});
        jInI = subsumes(EC{j},EC{i});
        if iInJ && jInI
            keep(j) = false;
        elseif iInJ
            keep(i) = false;
            break;
        elseif jInI
            keep(j) = false;
        end
    end
end
int_EC = EC(keep);
end
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
function tf = subsumes(general,specific)
%True if the code general is equal to or a wildcard parent of the code
%specific; both carry the "EC" prefix and need four levels.
general  = strsplit(extractAfter(general,2),'.');
specific = strsplit(extractAfter(specific,2),'.');
tf = false;
if numel(general) ~= 4 || numel(specific) ~= 4
    return;
end
for k = 1:4
    if strcmp(general{k},'-')
        tf = true;
        return;
    end
    if strcmp(specific{k},'-') || ~strcmp(general{k},specific{k})
        return;
    end
end
tf = true;
end
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
function int_EC = compare_wild(EC)
%Goes through a cell array of EC numbers, and erases any repetitions,
%considering also wildcards (e.g. will erase 'EC1.2.3.-' if 'EC1.2.3.4' is
%already present).

%Trim all EC numbers of wild cards (e.g. 'EC1.2.-.-' -> 'EC1.2.'):
EC_trimmed = EC;
for i = 1:length(EC)
    %Add a final dot for avoiding issues (e.g. 'EC1.1.1.1' & 'EC1.1.1.12'):
    ECi = [EC{i} '.'];
    pos = strfind(ECi,'-');
    if ~isempty(pos)
        ECi = ECi(1:pos(1)-1);
    end
    EC_trimmed{i} = ECi;
end

%Compare all EC numbers between them to find if 1 fits in the other:
non_repeated = true(1,length(EC));
for i = 1:length(EC)-1
    for j = i+1:length(EC)
        ECi = EC_trimmed{i};
        ECj = EC_trimmed{j};
        %If ECj fits in ECi then ECj can be disregarded:
        if strfind(ECi,ECj)
            non_repeated(j) = false;
        %Else, if ECi fits in ECj then ECi can be disregarded:
        elseif strfind(ECj,ECi)
            non_repeated(i) = false;
        end
    end
end

int_EC = EC(non_repeated);

end
